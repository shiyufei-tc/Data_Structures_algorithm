from typing import List
class Solution:
    def subarraySum(self, nums: List[int], k: int) -> int:
        """统计和恰好等于 ``k`` 的连续子数组个数。

        使用前缀和及其出现频次。设当前位置的前缀和为 ``Sum``，若某个更早
        的前缀和等于 ``Sum - k``，则两者之间的连续子数组之和恰好为 ``k``。
        字典记录已扫描前缀和的出现次数，因此每个位置都能一次性统计以它
        结尾的所有符合条件的子数组。该方法不要求数组元素为正数，也适用于
        含零或负数的输入。

        初始频次 ``{0: 1}`` 表示扫描任何元素之前，空前缀和为 0 出现一次；
        这也使从数组起点开始、总和为 ``k`` 的子数组能够被计入。

        Args:
            nums: 整数序列，可以包含正数、零或负数。
            k: 目标连续子数组和。

        Returns:
            和恰好等于 ``k`` 的连续子数组数量。

        Complexity:
            平均时间复杂度 O(n)，额外空间复杂度 O(n)，其中 n 为 ``nums``
            的长度。
        """
        # count 统计满足条件的连续子数组数量；Sum 是当前前缀和。
        count,Sum=0,0
        # 空前缀和为 0，先记录一次以覆盖从下标 0 开始的目标子数组。
        hash_map={0:1}
        for index in range(len(nums)):
            # 将当前元素加入前缀和，得到包含 nums[index] 的当前累计和。
            Sum+=nums[index]

            # 固定右端点后，每个更早的前缀位置都对应一个可能的左端点；
            # 该区间和 = 当前前缀和 - 左端点之前的前缀和。
            # 因而区间和为 k 的充要条件是：更早的前缀和等于 sum-k。
            # 表中 sum-k 的频次就是满足条件的左端点数，也就是以当前位置结尾的子数组数；
            # 将这些相同前缀和的左端点合并计数，避免为每个右端点重新枚举所有左端点。
            count+=hash_map.get(Sum-k,0)
            
            # 查询完成后再记录当前前缀，避免把空区间计作子数组。
            hash_map[Sum]=hash_map.get(Sum,0)+1
        return count
