class Solution:
    def merge(self, nums1: list[int], m: int, nums2: list[int], n: int) -> None:
        """将两个升序数组合并，并将结果原地写入 ``nums1``。

        ``nums1`` 的前 ``m`` 个元素和 ``nums2`` 的前 ``n`` 个元素是待合并
        的有效数据；``nums1`` 末尾预留了足够的位置存放合并结果。算法从
        两个有效区间的末尾开始比较，每次把较大的元素写入 ``nums1`` 当前
        可写的末尾位置，再向前移动对应的读取下标。由后向前写入可以避免
        覆盖 ``nums1`` 中尚未读取的元素。

        只需循环到 ``nums2`` 的有效元素全部写入。若此时 ``nums1`` 还有
        未处理元素，它们已经处在最终结果的正确位置，无须移动。

        Args:
            nums1: 结果数组。前 ``m`` 个元素为升序数据，且列表长度至少为
                ``m + n``；后续位置作为结果缓冲区。
            m: ``nums1`` 中参与合并的有效元素数量。
            nums2: 升序排列的第二个输入数组。
            n: ``nums2`` 中参与合并的有效元素数量。

        Returns:
            ``None``。合并结果直接修改 ``nums1``，其前 ``m + n`` 个元素
            按升序排列。

        Complexity:
            时间复杂度为 O(m + n)，额外空间复杂度为 O(1)。
        """
        # 将 m、n 转为各自有效区间的最后一个元素下标。
        m = m - 1
        n = n - 1
        # nums1 的最后一个预留位置是本轮合并结果的写入位置。
        idx = len(nums1) - 1

        # nums2 仍有元素时继续；nums1 剩余元素无需移动，已在正确位置。
        while n >= 0:
            # 若 nums1 还有未处理元素，且其末尾元素较大，则先将它放到结果末尾。
            if m >= 0 and nums1[m] > nums2[n]:
                nums1[idx] = nums1[m]
                m -= 1
            else:
                # 否则写入 nums2 的末尾元素；相等时先取 nums2 也不影响升序。
                nums1[idx] = nums2[n]
                n -= 1

            # 当前末尾位置已填好，下一次向左填充。
            idx -= 1
        