class Solution:
    def rotate(self, nums: list[int], k: int) -> None:
        """将列表中的元素整体向右轮转 ``k`` 个位置。

        右旋时，原列表末尾的 ``k`` 个元素会移动到列表开头，其余元素
        顺序不变。轮转长度等于列表长度时结果与原列表相同，因此先用
        ``k % len(nums)`` 计算实际需要移动的位置数。通过拼接两个切片
        构造轮转结果，再用整段切片赋值更新原列表，不会替换 ``nums`` 对象本身。

        Args:
            nums: 要轮转的非空整数列表；该列表会被原地修改。
            k: 非负的右旋位置数，可以大于列表长度。

        Returns:
            ``None``。结果直接写回 ``nums``。

        Complexity:
            时间复杂度 O(n)，额外空间复杂度 O(n)，其中 n 为列表长度；
            切片和拼接会创建临时列表。
        """
        # 将轮转次数缩减到 [0, len(nums))，避免重复执行完整轮转。
        k=k%len(nums)
        # 末尾 k 个元素移到开头，其余元素接在后面；整段赋值保留原列表对象。
        nums[:]=nums[-k:]+nums[:-k]